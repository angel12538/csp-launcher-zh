# ---------------------------------------------------------------- 编译

def build_table():
    """词级替换表，按长度降序（长词优先）。"""
    seen = {}
    for tw, cn in TERM_MAP:
        if tw == cn:
            continue          # 相同的不替换
        seen[tw] = cn
    return sorted(seen.items(), key=lambda kv: (-len(kv[0]), kv[0]))


def build_sentences():
    """整句重写表，按长度降序。"""
    seen = {}
    for tw, cn in SENTENCE_MAP:
        if tw == cn:
            continue
        seen[tw] = cn
    return sorted(seen.items(), key=lambda kv: (-len(kv[0]), kv[0]))


# ---------------------------------------------------------------- 替换执行

def has_japanese(text):
    """判断是否含日文假名。

    资源包里混有日文（GLSL 着色器注释、部分未翻译条目），若不加判断，
    「设定」「印刷」等词会误伤日文文本。

    注意排除符号区：
      U+30FB 「・」片假名中点 —— 中文排版里也常用作分隔符
      U+30FC 「ー」长音符   —— 偶尔出现在中文里
    只把真正的假名字母算作日文标识，否则「最新・推荐资讯」
    这类条目会因为一个中点被整体跳过。
    """
    for c in text:
        cp = ord(c)
        if 0x3041 <= cp <= 0x3096:      # 平假名字母
            return True
        if 0x30A1 <= cp <= 0x30FA:      # 片假名字母（不含 ・ ー）
            return True
    return False


_CACHE = {}


def _tables(table=None, sentences=None):
    if table is None or sentences is None:
        if "t" not in _CACHE:
            _CACHE["t"] = build_table()
            _CACHE["s"] = build_sentences()
        table = _CACHE["t"]
        sentences = _CACHE["s"]
    return table, sentences


def apply_terms(text, table):
    """只做词级替换。"""
    changed = 0
    for tw, cn in table:
        if tw in text:
            changed += text.count(tw)
            text = text.replace(tw, cn)
    return text, changed


def localize_text(text, table=None, sentences=None):
    """词级 + 整句两级本地化，返回 (新文本, 改动次数)。

    含假名的文本一律跳过——资源包里混有日文，盲目替换会破坏日文条目。
    """
    table, sentences = _tables(table, sentences)
    if has_japanese(text):
        return text, 0

    text, n1 = apply_terms(text, table)
    n2 = 0
    for tw, cn in sentences:
        if tw in text:
            n2 += text.count(tw)
            text = text.replace(tw, cn)
    return text, n1 + n2


