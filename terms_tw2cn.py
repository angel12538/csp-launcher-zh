def build_table():
    """返回按长度降序排序的替换表（长词优先）。"""
    seen = {}
    for tw, cn in TERM_MAP:
        if tw == cn:
            continue          # 相同的不替换
        seen[tw] = cn
    # 长词优先；同长度按字典序，保证结果稳定
    return sorted(seen.items(), key=lambda kv: (-len(kv[0]), kv[0]))


# ---------------------------------------------------------------- 替换执行

def has_japanese(text):
    """判断是否含日文假名。

    资源包里混有日文（GLSL 着色器注释、部分未翻译条目），若不加判断，
    「设定」「印刷」等词会误伤日文文本。

    注意排除符号区：
      U+30FB 「・」片假名中点 —— 中文排版里也常用作分隔符
      U+30FC 「ー」长音符   —— 偶尔出现在中文里
    只把真正的假名字母算作日文标识，否则「最新・推荐资讯」
    这类条目会因为一个中点被整体跳过。
    """
    for c in text:
        cp = ord(c)
        if 0x3041 <= cp <= 0x3096:      # 平假名字母
            return True
        if 0x30A1 <= cp <= 0x30FA:      # 片假名字母（不含 ・ ー）
            return True
    return False


_TABLE_CACHE = None


def localize_text(text, table=None):
    """按长词优先替换，返回 (新文本, 改动次数)。

    含假名的文本一律跳过——资源包里混有日文，盲目替换会破坏日文条目。
    """
    global _TABLE_CACHE
    if table is None:
        if _TABLE_CACHE is None:
            _TABLE_CACHE = build_table()
        table = _TABLE_CACHE
    if has_japanese(text):
        return text, 0

    changed = 0
    for tw, cn in table:
        if tw in text:
            n = text.count(tw)
            text = text.replace(tw, cn)
            changed += n
    return text, changed


