# 明确禁用的（字数不等）——留作记录，说明为什么不用
DISABLED_WORDCOUNT_MISMATCH = [
    ("记忆体", "内存"),
    ("点阵图", "位图"),
    ("透明度", "不透明度"),
    ("彩度", "饱和度"),
    ("全萤幕", "全屏"),
    ("浮水印", "水印"),
    ("锐利化", "锐化"),
    ("功能表", "菜单"),
    ("素材夹", "素材库"),
]


def build_table():
    """返回按长度降序排序的替换表（长词优先）。"""
    seen = {}
    for tw, cn in TERM_MAP:
        if tw == cn:
            continue  # 相同的不替换
        if len(tw) != len(cn):
            continue  # 字数不等，跳过（硬约束）
        seen[tw] = cn
    # 长词优先
    items = sorted(seen.items(), key=lambda kv: (-len(kv[0]), kv[0]))
    return items


if __name__ == "__main__":
    t = build_table()
    print(f"可用替换规则: {len(t)} 条\n")
    for tw, cn in t:
        print(f"  {tw} -> {cn}")
    print(f"\n因字数不等而禁用: {len(DISABLED_WORDCOUNT_MISMATCH)} 条")
    for tw, cn in DISABLED_WORDCOUNT_MISMATCH:
        print(f"  {tw} -> {cn}  ({len(tw)}->{len(cn)})")
